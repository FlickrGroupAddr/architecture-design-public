"""Generate deterministic thumbnail fixtures for the Lightroom selector probe."""

from __future__ import annotations

import argparse
import struct
import zlib
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT_DIRECTORY = (
    REPOSITORY_ROOT / "lightroom" / "FGA Diagnostics.lrdevplugin" / "selector-fixtures"
)
WIDTH = 160
HEIGHT = 120

type Color = tuple[int, int, int]


@dataclass(frozen=True)
class FixtureSpec:
    """One visually distinct generated thumbnail."""

    filename: str
    background: Color
    foreground: Color
    accent: Color
    motif: int


FIXTURES = (
    FixtureSpec("thumbnail-01.png", (44, 104, 160), (245, 188, 77), (236, 244, 248), 0),
    FixtureSpec("thumbnail-02.png", (115, 52, 77), (232, 149, 89), (253, 226, 160), 1),
    FixtureSpec("thumbnail-03.png", (43, 96, 73), (128, 172, 104), (222, 214, 170), 2),
    FixtureSpec("thumbnail-04.png", (67, 46, 118), (188, 85, 150), (238, 211, 235), 3),
    FixtureSpec("thumbnail-05.png", (30, 82, 116), (72, 164, 187), (238, 245, 224), 4),
    FixtureSpec("thumbnail-06.png", (64, 68, 75), (168, 174, 181), (244, 205, 91), 5),
)

type MotifRenderer = Callable[[FixtureSpec, int, int], Color]


def _png_chunk(chunk_type: bytes, payload: bytes) -> bytes:
    contents = chunk_type + payload
    checksum = zlib.crc32(contents) & 0xFFFFFFFF
    return struct.pack(">I", len(payload)) + contents + struct.pack(">I", checksum)


def _horizon(spec: FixtureSpec, x: int, y: int) -> Color:
    if y > HEIGHT * 2 // 3:
        return spec.foreground
    in_window = WIDTH // 8 < x < WIDTH * 11 // 32 and HEIGHT // 8 < y < HEIGHT * 5 // 12
    return spec.accent if in_window else spec.background


def _diagonal(spec: FixtureSpec, x: int, y: int) -> Color:
    if abs((x * HEIGHT // WIDTH) - y) < HEIGHT // 10:
        return spec.accent
    return spec.foreground if x > WIDTH * 2 // 3 else spec.background


def _grid(spec: FixtureSpec, x: int, y: int) -> Color:
    if (x // 24 + y // 24) % 2 == 0:
        return spec.foreground
    return spec.accent if y > HEIGHT * 3 // 4 else spec.background


def _circle(spec: FixtureSpec, x: int, y: int) -> Color:
    radius = 38
    if (x - WIDTH // 2) ** 2 + (y - HEIGHT // 2) ** 2 < radius**2:
        return spec.accent
    return spec.foreground if (x // 16) % 2 == 0 else spec.background


def _cross(spec: FixtureSpec, x: int, y: int) -> Color:
    horizontal_half_width = 14
    vertical_half_width = 10
    if abs(x - WIDTH // 2) < horizontal_half_width or abs(y - HEIGHT // 2) < vertical_half_width:
        return spec.accent
    return spec.foreground if (x // 20 + y // 15) % 3 == 0 else spec.background


def _bars(spec: FixtureSpec, x: int, y: int) -> Color:
    if (x // 18) % 2 == 0:
        return spec.foreground
    in_band = HEIGHT * 7 // 20 < y < HEIGHT * 13 // 20
    return spec.accent if in_band else spec.background


MOTIF_RENDERERS: tuple[MotifRenderer, ...] = (
    _horizon,
    _diagonal,
    _grid,
    _circle,
    _cross,
    _bars,
)


def _pixel(spec: FixtureSpec, x: int, y: int) -> Color:
    """Return a high-contrast geometric pixel for one fixture motif."""

    return MOTIF_RENDERERS[spec.motif](spec, x, y)


def fixture_bytes(spec: FixtureSpec) -> bytes:
    """Encode one fixture as a non-interlaced 8-bit RGB PNG."""

    raw = bytearray()
    for y in range(HEIGHT):
        raw.append(0)
        for x in range(WIDTH):
            raw.extend(_pixel(spec, x, y))

    header = struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, 2, 0, 0, 0)
    return b"".join(
        (
            b"\x89PNG\r\n\x1a\n",
            _png_chunk(b"IHDR", header),
            _png_chunk(b"IDAT", zlib.compress(bytes(raw), level=9)),
            _png_chunk(b"IEND", b""),
        )
    )


def write_fixtures(output_directory: Path = DEFAULT_OUTPUT_DIRECTORY) -> None:
    """Write every fixture, replacing only the known generated filenames."""

    output_directory.mkdir(parents=True, exist_ok=True)
    for spec in FIXTURES:
        (output_directory / spec.filename).write_bytes(fixture_bytes(spec))


def check_fixtures(output_directory: Path = DEFAULT_OUTPUT_DIRECTORY) -> list[str]:
    """Return fixture filenames that are missing or differ from generated bytes."""

    return [
        spec.filename
        for spec in FIXTURES
        if not (output_directory / spec.filename).is_file()
        or (output_directory / spec.filename).read_bytes() != fixture_bytes(spec)
    ]


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if committed fixtures do not match the generator",
    )
    return parser.parse_args()


def main() -> None:
    """Generate or verify the committed fixture set."""

    args = parse_args()
    if args.check:
        mismatches = check_fixtures()
        if mismatches:
            joined = ", ".join(mismatches)
            raise SystemExit(f"Selector fixtures are missing or stale: {joined}")
        print(f"Verified {len(FIXTURES)} selector fixtures.")
        return

    write_fixtures()
    print(f"Wrote {len(FIXTURES)} selector fixtures to {DEFAULT_OUTPUT_DIRECTORY}.")


if __name__ == "__main__":
    main()
